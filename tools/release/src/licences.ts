// Split out of release-audit.ts. The licence inventory needs the lockfile and
// one markdown file; everything else in that audit needs a production build,
// so it only ran weekly and at tag time. A dependency bump therefore passed
// the fast gate and broke the next weekly run -- which is exactly what the
// 2026-10-25 group bump did, going red on @noble/hashes@2.4.0 after merging
// green. Here the same checks cost an install and a second, so the fast gate
// can run them on the pull request that causes the drift.
//
// The table is generated rather than hand-written. pnpm already knows every
// production version; asking a human to retype eight of them is asking for
// the drift back.

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const REPOSITORY_ROOT = resolve(dirname(import.meta.filename), "../../..");
const NOTICES_FILE = "THIRD_PARTY_NOTICES.md";
const TABLE_BEGIN = "<!-- licences:begin (generated by pnpm licences:write) -->";
const TABLE_END = "<!-- licences:end -->";

interface LicenseListEntry {
  readonly name: string;
  readonly versions: readonly string[];
  readonly license: string;
  readonly author?: string;
  readonly homepage?: string;
}

export interface ProductionLicenseRecord {
  readonly package: string;
  readonly version: string;
  readonly licence: string;
  readonly author?: string;
  readonly homepage?: string;
}

export function readProductionLicences(root: string): readonly ProductionLicenseRecord[] {
  const listed = spawnSync("pnpm", ["licenses", "list", "--prod", "--json"], {
    cwd: root,
    encoding: "utf8",
  });
  if (listed.error !== undefined) throw listed.error;
  if (listed.status !== 0) {
    throw new Error(`pnpm licence inventory failed: ${listed.stderr}`);
  }
  const buckets = JSON.parse(listed.stdout) as Record<string, LicenseListEntry[]>;
  return Object.entries(buckets)
    .flatMap(([bucket, entries]) =>
      entries.flatMap((entry) =>
        entry.versions.map((version) => ({
          package: entry.name,
          version,
          licence: entry.license || bucket,
          ...(entry.author === undefined ? {} : { author: entry.author }),
          ...(entry.homepage === undefined ? {} : { homepage: entry.homepage }),
        })),
      ),
    )
    .sort((left, right) =>
      `${left.package}@${left.version}`.localeCompare(
        `${right.package}@${right.version}`,
      ),
    );
}

export function renderNoticesTable(records: readonly ProductionLicenseRecord[]): string {
  // Sorted by name and then version, which is not the audit's own
  // package@version order: that puts react-dom ahead of react, because "-"
  // precedes "@". This table is read by people.
  const ordered = [...records].sort(
    (left, right) =>
      left.package.localeCompare(right.package) ||
      left.version.localeCompare(right.version),
  );
  return [
    TABLE_BEGIN,
    "",
    "| Component | Version | Licence |",
    "|---|---:|---|",
    ...ordered.map(
      (record) => `| \`${record.package}\` | ${record.version} | ${record.licence} |`,
    ),
    "",
    TABLE_END,
  ].join("\n");
}

// The markers are HTML comments so the rendered document is unchanged, and the
// region is replaced wholesale: a generator that tried to patch individual rows
// would have to guess what a human meant by a row pnpm no longer reports.
export function replaceNoticesTable(notices: string, table: string): string {
  const begin = notices.indexOf(TABLE_BEGIN);
  const end = notices.indexOf(TABLE_END);
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(
      `${NOTICES_FILE} is missing its generated table markers (${TABLE_BEGIN} … ${TABLE_END})`,
    );
  }
  return notices.slice(0, begin) + table + notices.slice(end + TABLE_END.length);
}

export function writeNotices(root: string): boolean {
  const path = join(root, NOTICES_FILE);
  const current = readFileSync(path, "utf8");
  const updated = replaceNoticesTable(
    current,
    renderNoticesTable(readProductionLicences(root)),
  );
  if (updated === current) return false;
  writeFileSync(path, updated);
  return true;
}

// Fails closed on three separable mistakes, each with its own message: a table
// that no longer matches the lockfile, a package whose licence or copyright was
// never recorded, and a missing copyright notice. Only the first is routine.
export function verifyNotices(root: string): readonly ProductionLicenseRecord[] {
  const records = readProductionLicences(root);
  if (records.length === 0 || records.some((record) => record.licence.trim() === "")) {
    throw new Error("Production dependency licence inventory is incomplete");
  }
  const current = readFileSync(join(root, NOTICES_FILE), "utf8");
  const expected = replaceNoticesTable(current, renderNoticesTable(records));
  if (expected !== current) {
    throw new Error(
      `${NOTICES_FILE} no longer matches the production lockfile. Run \`pnpm licences:write\` and commit the result.`,
    );
  }
  verifyThirdPartyNotices(root, records);
  return records;
}

export function verifyThirdPartyNotices(
  root: string,
  records: readonly ProductionLicenseRecord[],
): void {
  const notices = readFileSync(join(root, NOTICES_FILE), "utf8");
  for (const record of records) {
    for (const expected of [record.package, record.version, record.licence]) {
      if (!notices.includes(expected)) {
        throw new Error(
          `Third-party notices omit ${record.package}@${record.version} ${record.licence}`,
        );
      }
    }
  }
  // Keyed to packages rather than versions, so a bump never touches this list;
  // adding or removing a production dependency does, and should stop a human.
  const requiredCopyrightNotices = [
    "Copyright © 2022 Paul Miller",
    "Copyright © Microsoft Corporation",
    "Copyright © 2017–2018 Fredrik Nicol",
    "Copyright © Meta Platforms, Inc. and affiliates",
    "Copyright © 2025 Colin McDonnell",
    "Copyright © 2019 Paul Henschel",
    "Copyright Eemeli Aro",
    "Copyright 2016 The Inter Project Authors",
    "Copyright 2020 The JetBrains Mono",
  ];
  for (const notice of requiredCopyrightNotices) {
    if (!notices.includes(notice)) {
      throw new Error(`Third-party copyright notice is missing: ${notice}`);
    }
  }
}

function main(argv: readonly string[]): void {
  const write = argv.includes("--write");
  if (write) {
    const changed = writeNotices(REPOSITORY_ROOT);
    console.log(
      changed
        ? `${NOTICES_FILE}: regenerated the production dependency table`
        : `${NOTICES_FILE}: already matches the production lockfile`,
    );
    return;
  }
  const records = verifyNotices(REPOSITORY_ROOT);
  console.log(
    `${NOTICES_FILE}: ${records.length} production packages match the lockfile`,
  );
}

if (import.meta.filename === process.argv[1]) {
  main(process.argv.slice(2));
}
