import { describe, expect, it } from "vitest";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import {
  renderNoticesTable,
  replaceNoticesTable,
  verifyThirdPartyNotices,
  type ProductionLicenseRecord,
} from "./licences.ts";

const RECORDS: readonly ProductionLicenseRecord[] = [
  { package: "@noble/hashes", version: "2.4.0", licence: "MIT" },
  { package: "yaml", version: "2.9.1", licence: "ISC" },
];

const REQUIRED_COPYRIGHTS = [
  "Copyright © 2022 Paul Miller",
  "Copyright © Microsoft Corporation",
  "Copyright © 2017–2018 Fredrik Nicol",
  "Copyright © Meta Platforms, Inc. and affiliates",
  "Copyright © 2025 Colin McDonnell",
  "Copyright © 2019 Paul Henschel",
  "Copyright Eemeli Aro",
  "Copyright 2016 The Inter Project Authors",
  "Copyright 2020 The JetBrains Mono",
].join("\n");

function noticesFixture(table: string): string {
  return `# Third-party notices\n\n${table}\n\n${REQUIRED_COPYRIGHTS}\n`;
}

function withTemporaryRoot(notices: string, body: (root: string) => void): void {
  const root = mkdtempSync(join(tmpdir(), "neolab-licences-"));
  try {
    writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), notices);
    body(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

describe("production licence notices", () => {
  it("renders one table row per production package", () => {
    expect(renderNoticesTable(RECORDS)).toBe(
      [
        "<!-- licences:begin (generated by pnpm licences:write) -->",
        "",
        "| Component | Version | Licence |",
        "|---|---:|---|",
        "| `@noble/hashes` | 2.4.0 | MIT |",
        "| `yaml` | 2.9.1 | ISC |",
        "",
        "<!-- licences:end -->",
      ].join("\n"),
    );
  });

  it("replaces the generated region and leaves the surrounding prose alone", () => {
    const stale = noticesFixture(
      renderNoticesTable([
        { package: "@noble/hashes", version: "2.2.0", licence: "MIT" },
      ]),
    );
    const refreshed = replaceNoticesTable(stale, renderNoticesTable(RECORDS));
    expect(refreshed).toContain("# Third-party notices");
    expect(refreshed).toContain("| `yaml` | 2.9.1 | ISC |");
    expect(refreshed).not.toContain("2.2.0");
  });

  it("refuses a notices file whose generated markers are missing", () => {
    expect(() =>
      replaceNoticesTable("# Third-party notices\n", renderNoticesTable(RECORDS)),
    ).toThrow(/missing its generated table markers/);
  });

  it("accepts notices that cover every production record", () => {
    withTemporaryRoot(noticesFixture(renderNoticesTable(RECORDS)), (root) => {
      expect(() => verifyThirdPartyNotices(root, RECORDS)).not.toThrow();
    });
  });

  // The failure that took the 2026-10-25 weekly run down: a bumped version the
  // notices file had never heard of.
  it("names the package whose version the notices omit", () => {
    const stale = noticesFixture(
      renderNoticesTable([
        { package: "@noble/hashes", version: "2.2.0", licence: "MIT" },
        { package: "yaml", version: "2.9.1", licence: "ISC" },
      ]),
    );
    withTemporaryRoot(stale, (root) => {
      expect(() => verifyThirdPartyNotices(root, RECORDS)).toThrow(
        "Third-party notices omit @noble/hashes@2.4.0 MIT",
      );
    });
  });

  it("reports a copyright notice that was never recorded", () => {
    const withoutMeta = noticesFixture(renderNoticesTable(RECORDS)).replace(
      "Copyright © Meta Platforms, Inc. and affiliates\n",
      "",
    );
    withTemporaryRoot(withoutMeta, (root) => {
      expect(() => verifyThirdPartyNotices(root, RECORDS)).toThrow(
        /copyright notice is missing: Copyright © Meta Platforms/,
      );
    });
  });
});
